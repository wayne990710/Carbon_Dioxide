import math
from collections import Counter

def descriptive_statistics(text_block):
    # 1. 解析資料
    try:
        data = [float(x) for x in text_block.strip().split("\n") if x.strip()]
    except ValueError as e:
        print(f"錯誤：資料中包含非數字字元。內容：{e}")
        return None

    n = len(data)
    if n == 0:
        print("錯誤：輸入資料為空。")
        return None

    # 2. 基礎排序與極值
    sorted_data = sorted(data)
    max_val = sorted_data[-1]
    min_val = sorted_data[0]

    # 3. 計算中位數 (Median)
    def get_median(lst):
        m = len(lst)
        if m % 2 == 1:
            return lst[m // 2]
        else:
            return (lst[m // 2 - 1] + lst[m // 2]) / 2

    median_val = get_median(sorted_data)

    # 4. 計算四分位數與 IQR
    mid = n // 2
    if n % 2 == 1:
        lower_half = sorted_data[:mid]
        upper_half = sorted_data[mid+1:]
    else:
        lower_half = sorted_data[:mid]
        upper_half = sorted_data[mid:]

    q1 = get_median(lower_half)
    q3 = get_median(upper_half)
    iqr = q3 - q1
    lower_bound = q1 - 1.5 * iqr
    upper_bound = q3 + 1.5 * iqr

    # 5. 計算眾數 (Mode)
    counts = Counter(data)
    max_count = max(counts.values())
    # 若所有數值出現次數都一樣，通常視為無眾數，但在統計程式中一般會列出
    if max_count == 1 and n > 1:
        mode_val = "無重複數值"
    else:
        mode_val = [k for k, v in counts.items() if v == max_count]

    # 6. 計算平均、標準差、標準誤差
    mean_val = sum(data) / n
    outliers = [x for x in data if x < lower_bound or x > upper_bound]

    if n > 1:
        variance = sum((x - mean_val) ** 2 for x in data) / (n - 1)
        sd_val = math.sqrt(variance)
        se_val = sd_val / math.sqrt(n)
    else:
        sd_val = 0.0
        se_val = 0.0

    # 7. 輸出結果
    print("========= 描述性統計結果 =========")
    print(f"中位數 (Median): {median_val}")
    print(f"平均值 (Mean): {mean_val:.4f}")
    print(f"第一四分位數 (Q1): {q1}")
    print(f"第三四分位數 (Q3): {q3}")
    print(f"最小值 (Min): {min_val}")
    print(f"最大值 (Max): {max_val}")
    print(f"離群值判定邊界 (Lower/Upper): {lower_bound:.2f} / {upper_bound:.2f}")
    print(f"標準差 (SD): {sd_val:.4f}")
    print(f"樣本總數 (n): {n}")
    print("--------------------------------")
    print(f"全距 (Range): {max_val - min_val}")
    print(f"眾數 (Mode): {mode_val}")
    print(f"標準誤差 (SE): {se_val:.4f}")
    print(f"四分位距 (IQR): {iqr}")
    print(f"偵測到離群值 (Outliers): {outliers}")
    print("================================")

    return data

